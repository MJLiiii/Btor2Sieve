"""scripts/convert_legacy_btor2.py: legacy Yosys BTOR2 to current BTOR2, checked by isomorphism.

Pono (on PATH, inside nix-shell) must read every converted model."""

import importlib.util
from pathlib import Path
import sys

import pytest

from btor2sieve.pono import check_readable, scan


def _readable(text: str, tmp_path: Path) -> None:
    path = tmp_path / "model.btor2"
    path.write_text(text)
    check_readable("pono", path)


def _ops(text: str, op: str):
    return [line for line in scan(text) if line.op == op]


ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("convert_legacy_btor2", ROOT / "scripts/convert_legacy_btor2.py")
convert_legacy = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = convert_legacy  # dataclasses look up their defining module
_spec.loader.exec_module(convert_legacy)

# Exercises every legacy feature: an output with a sort, `ne`, and an init
# value (line 8) defined after its state (line 7).
LEGACY = """\
; BTOR description generated by Yosys 0.7 for module test.
1 sort bitvec 1
2 sort bitvec 4
3 input 2 x
4 state 2 s
5 zero 2
6 init 2 4 5
7 state 2 t
8 const 2 0011
9 init 2 7 8
10 output 2 4 s_out
11 ne 1 4 7
12 bad 11 b0
13 add 2 4 3
14 next 2 4 13
15 next 2 7 7
16 sort array 2 2
17 state 16 mem
18 init 16 17 5
19 read 2 17 3
20 eq 1 19 7
21 bad 20 b1
22 constraint -11
; end of yosys output
"""


def test_legacy_sample_is_rejected_by_pono_without_conversion(tmp_path):
    with pytest.raises(ValueError):
        _readable(LEGACY, tmp_path)


def test_conversion_is_read_by_pono_and_preserves_structure(tmp_path):
    text, mapping = convert_legacy.convert(LEGACY, "sample.btor")
    _readable(text, tmp_path)
    assert [line.words[-1] for line in _ops(text, "bad")] == ["b0", "b1"]
    assert [line.words[-1] for line in _ops(text, "state")] == ["s", "t", "mem"]
    (constraint,) = _ops(text, "constraint")
    assert int(constraint.words[0]) < 0
    assert "ne " not in text and " neq " in text
    (output,) = _ops(text, "output")
    assert output.words == (str(mapping[4]), "s_out")
    init_t = next(line for line in _ops(text, "init") if int(line.words[1]) == mapping[7])
    assert int(init_t.words[2]) == mapping[8] < mapping[7]
    assert text.startswith("; BTOR description generated by Yosys 0.7")
    assert len(mapping) == 22


def test_current_btor2_is_unchanged_apart_from_header():
    current = "1 sort bitvec 1\n2 state 1 flag\n3 bad 2\n"
    text, mapping = convert_legacy.convert(current)
    assert mapping == {1: 1, 2: 2, 3: 3}
    assert text.splitlines()[1:] == current.splitlines()


def test_check_rejects_a_tampered_conversion(tmp_path):
    text, mapping = convert_legacy.convert(LEGACY)
    _, original = convert_legacy.read(LEGACY)
    tampered = text.replace("const 2 0011", "const 2 0101")  # Pono reads it; a different model.
    _readable(tampered, tmp_path)
    assert tampered != text
    with pytest.raises(convert_legacy.ConversionError, match="line 9: converted line differs"):
        convert_legacy.check(original, tampered, mapping)
    flipped = text.replace(f"constraint -{mapping[11]}", f"constraint {mapping[11]}")
    assert flipped != text
    with pytest.raises(convert_legacy.ConversionError, match="differs"):
        convert_legacy.check(original, flipped, mapping)


def test_check_rejects_reordered_properties():
    text, mapping = convert_legacy.convert("1 sort bitvec 1\n2 input 1 a\n3 input 1 b\n4 bad 2 p\n5 bad 3 q\n")
    _, original = convert_legacy.read("1 sort bitvec 1\n2 input 1 a\n3 input 1 b\n4 bad 2 p\n5 bad 3 q\n")
    reordered = text.replace("4 bad 2 p\n5 bad 3 q", "4 bad 3 q\n5 bad 2 p")
    with pytest.raises(convert_legacy.ConversionError):
        convert_legacy.check(original, reordered, {1: 1, 2: 2, 3: 3, 4: 5, 5: 4})


def test_init_depending_on_its_own_state_is_a_cycle():
    model = "1 sort bitvec 4\n2 state 1 s\n3 one 1\n4 add 1 2 3\n5 init 1 2 4\n"
    with pytest.raises(convert_legacy.ConversionError, match="cycle"):
        convert_legacy.convert(model)


@pytest.mark.parametrize("model, message", [
    ("1 sort bitvec 1\n2 frobnicate 1\n", "unsupported operation 'frobnicate'"),
    ("1 sort bitvec 1\n2 state 1 a b\n", "at most one symbol"),
    ("1 sort bitvec 1\n2 not 1 7\n", "undefined reference 7"),
])
def test_invalid_legacy_input(model, message):
    with pytest.raises(convert_legacy.ConversionError, match=message):
        convert_legacy.convert(model)


def test_cli_writes_btor2_and_refuses_to_overwrite(tmp_path, capsys):
    source = tmp_path / "legacy" / "sample.btor"
    source.parent.mkdir()
    source.write_text(LEGACY)
    out = tmp_path / "converted"
    assert convert_legacy.main([str(source), "--out", str(out)]) == 0
    assert len(_ops((out / "sample.btor2").read_text(), "bad")) == 2
    before = (out / "sample.btor2").read_text()
    with pytest.raises(SystemExit):
        convert_legacy.main([str(source), "--out", str(out)])
    assert (out / "sample.btor2").read_text() == before
    assert "refusing to overwrite" in capsys.readouterr().err


def test_cli_writes_nothing_when_any_source_fails(tmp_path):
    good, bad = tmp_path / "good.btor", tmp_path / "bad.btor"
    good.write_text(LEGACY)
    bad.write_text("1 sort bitvec 1\n2 frobnicate 1\n")
    out = tmp_path / "converted"
    assert convert_legacy.main([str(good), str(bad), "--out", str(out)]) == 1
    assert not out.exists()


# Property counts from Table 2 of Niemetz, Preiner, Wolf, Biere, CAV 2018.
CAV18 = {
    "multi/arrays/picorv32-check.btor2": 23,
    "multi/arrays/picorv32-pcregs.btor2": 3,
    "single/arrays/ponylink-slaveTXlen-sat.btor2": 1,
    "single/arrays/ponylink-slaveTXlen-unsat.btor2": 1,
    "multi/arrays/VexRiscv-regch0-15.btor2": 2,
    "multi/arrays/VexRiscv-regch0-20.btor2": 2,
    "multi/arrays/VexRiscv-regch0-30.btor2": 2,
    "multi/arrays/zipcpu-pfcache.btor2": 39,
    "multi/arrays/zipcpu-zipmmu.btor2": 57,
    "multi/bv/zipcpu-busdelay.btor2": 50,
}


@pytest.mark.parametrize("path, bads", sorted(CAV18.items()))
def test_local_cav18_models_have_paper_property_counts(path, bads):
    file = ROOT / "benchmarks/cav18/2018" / path
    if not file.exists():
        pytest.skip("CAV'18 models not converted locally; see benchmarks/README.md")
    text = file.read_text()
    assert len(_ops(text, "bad")) == bads
    has_arrays = any(line.words[:1] == ("array",) for line in _ops(text, "sort"))
    assert has_arrays == ("/arrays/" in path)
